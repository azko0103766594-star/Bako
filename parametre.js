const Settings = {
  lang: localStorage.getItem('align_lang') || 'fr',
  theme: localStorage.getItem('align_theme') || 'dark',

  t(key) {
    return (I18N[this.lang] && I18N[this.lang][key]) || I18N.fr[key] || key;
  },

  applyLanguage() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = this.t(key);
      if (val) el.innerHTML = val;
    });

    // Extra dynamic texts that don't have data-i18n yet
    const map = {
      'empty-spaces': ['empty_spaces', 'empty_spaces2'],
      'btn-save-profile': 'continue_btn'
    };

    // Update tab labels if present
    document.querySelectorAll('.private-tab').forEach(tab => {
      const f = tab.dataset.filter;
      if (f === 'all') tab.textContent = this.t('tab_all');
      if (f === 'pinned') tab.textContent = this.t('tab_pinned');
      if (f === 'archived') tab.textContent = this.t('tab_archived');
    });

    // Space tabs
    document.querySelectorAll('.tab').forEach(tab => {
      const t = tab.dataset.tab;
      if (t === 'discussion') tab.textContent = this.t('discussion');
      if (t === 'plans') tab.textContent = this.t('plans');
      if (t === 'infos') tab.textContent = this.t('infos');
    });

    // Placeholders
    const search = document.getElementById('private-search');
    if (search) search.placeholder = this.t('search_conv');

    document.documentElement.lang = this.lang;
  },

  setLanguage(lang) {
    if (!I18N[lang]) return;
    this.lang = lang;
    localStorage.setItem('align_lang', lang);
    this.applyLanguage();

    document.querySelectorAll('.lang-btn').forEach(b => {
      b.classList.toggle('active', b.dataset.lang === lang);
    });

    if (typeof toast === 'function') toast(this.t('toast_lang'));
  },

  applyTheme() {
    document.body.classList.toggle('theme-light', this.theme === 'light');
    document.querySelectorAll('.theme-btn').forEach(b => {
      b.classList.toggle('active', b.dataset.theme === this.theme);
    });
  },

  setTheme(theme) {
    this.theme = theme;
    localStorage.setItem('align_theme', theme);
    this.applyTheme();
    if (typeof toast === 'function') {
      toast(theme === 'light' ? this.t('toast_theme_light') : this.t('toast_theme_dark'));
    }
  },

  getShareUrl() {
    return window.location.origin + window.location.pathname;
  },

  getShareText() {
    const texts = {
      fr: 'Rejoins-moi sur Align ! Organise tes groupes sans le bordel 🚀',
      en: 'Join me on Align! Organize your groups without the mess 🚀',
      es: '¡Únete a mí en Align! Organiza tus grupos sin el desorden 🚀',
      de: 'Komm zu Align! Organisiere deine Gruppen ohne Chaos 🚀'
    };
    return texts[this.lang] || texts.fr;
  },

  shareWhatsApp() {
    const url = encodeURIComponent(this.getShareUrl());
    const text = encodeURIComponent(this.getShareText());
    window.open(`https://wa.me/?text=${text}%20${url}`, '_blank');
  },

  shareFacebook() {
    const url = encodeURIComponent(this.getShareUrl());
    window.open(`https://www.facebook.com/sharer/sharer.php?u=${url}`, '_blank');
  },

  shareInstagram() {
    // Instagram doesn't support direct web share of links easily → copy link
    const url = this.getShareUrl();
    if (navigator.clipboard) {
      navigator.clipboard.writeText(url).then(() => {
        if (typeof toast === 'function') toast(this.t('toast_share_copied') + ' (Instagram)');
      });
    } else {
      prompt('Copie ce lien pour Instagram :', url);
    }
  },

  init() {
    this.applyLanguage();
    this.applyTheme();

    // Language buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.classList.toggle('active', btn.dataset.lang === this.lang);
      btn.onclick = () => this.setLanguage(btn.dataset.lang);
    });

    // Theme buttons
    document.querySelectorAll('.theme-btn').forEach(btn => {
      btn.onclick = () => this.setTheme(btn.dataset.theme);
    });

    // Share buttons
    const wa = document.getElementById('btn-share-whatsapp');
    const fb = document.getElementById('btn-share-facebook');
    const ig = document.getElementById('btn-share-instagram');
    if (wa) wa.onclick = () => this.shareWhatsApp();
    if (fb) fb.onclick = () => this.shareFacebook();
    if (ig) ig.onclick = () => this.shareInstagram();

    // Settings navigation
    const btnSettings = document.getElementById('btn-settings');
    const btnBack = document.getElementById('btn-back-settings');
    if (btnSettings) {
      btnSettings.onclick = () => {
        if (typeof show === 'function') show('screen-settings');
      };
    }
    if (btnBack) {
      btnBack.onclick = () => {
        if (typeof show === 'function') show('screen-home');
      };
    }
  }
};

// Init when DOM ready (app.js also listens to DOMContentLoaded)
document.addEventListener('DOMContentLoaded', () => {
  Settings.init();
});
